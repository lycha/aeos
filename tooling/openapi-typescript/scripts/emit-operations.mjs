// Optional operations-registry emitter, wired in via the policy's `afterGenerate` hook.
//
// It writes `<out>/operations.gen.ts`: one `OperationDefinition` per operationId that binds the
// generated Zod validators to the operation's method, path, declared statuses and content types.
// This part is PORTABLE - it is derived from the spec plus the generated validator names, with no
// assumption about how the app routes.
//
// Everything framework-specific comes from an ADAPTER (see adapters/). An adapter can:
//   - fields(op)   -> extra literal fields merged into each registry entry (e.g. Next's routeFile),
//   - typeFields   -> the TS members those fields add to the OperationDefinition interface,
//   - emit(ctx)    -> write extra framework files (e.g. Fastify's operationId union + 501 stubs),
//   - check(op,ctx)-> a per-operation conformance check, thrown on violation.
// All four are optional, so a routing-agnostic project passes no adapter at all.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const pascal = (id) => id.charAt(0).toUpperCase() + id.slice(1);
const literal = (v) => JSON.stringify(v);

/** Classify a declared response code. 1xx/3xx get no generated schema and are ignored here. */
const statusesOf = (operation) => {
  const codes = Object.keys(operation.responses ?? {})
    .filter((c) => /^[1-5]\d\d$/.test(c))
    .map(Number);
  return {
    successStatuses: codes.filter((c) => c >= 200 && c < 300).sort((a, b) => a - b),
    errorStatuses: codes.filter((c) => c >= 400 && c < 600).sort((a, b) => a - b),
  };
};

/**
 * Build the portable registry entries from the walk results. Pure and exported for tests.
 * Throws (plain Error) if a validator the naming convention predicts is not actually exported -
 * that means a generator upgrade changed hey-api's `z<Pascal(operationId)>…` rule.
 */
export function buildRegistry(operations, zodExports, adapter) {
  return operations.map((op) => {
    const P = pascal(op.operationId);
    const params = op.parameters ?? [];
    const has = (loc) => params.some((p) => p && p.in === loc);

    const schemas = {
      body: op.requestBody !== undefined ? `z${P}Body` : null,
      pathParams: has("path") ? `z${P}Path` : null,
      query: has("query") ? `z${P}Query` : null,
      headers: has("header") ? `z${P}Headers` : null,
      response: `z${P}Response`,
    };
    const unexported = Object.values(schemas).filter((n) => n && !zodExports.has(n));
    if (unexported.length) {
      throw new Error(
        `${op.operationId}: expected ${unexported.join(", ")} in zod.gen.ts, but they are not exported. ` +
          `The names are PascalCase(operationId) + role, a hey-api convention - a generator upgrade may have changed it.`,
      );
    }

    const { successStatuses, errorStatuses } = statusesOf(op.operation);
    const fields = adapter?.fields ? adapter.fields(op) : {};

    return {
      operationId: op.operationId,
      method: op.method,
      path: op.path,
      successStatuses,
      errorStatuses,
      requestContentTypes: Object.keys(op.requestBody?.content ?? {}),
      headerNames: params.filter((p) => p.in === "header").map((p) => p.name),
      schemas,
      fields,
    };
  });
}

/** Render operations.gen.ts. Pure and exported for tests. */
export function renderRegistry(entries, adapter) {
  const imports = [...new Set(entries.flatMap((e) => Object.values(e.schemas).filter(Boolean)))].sort();
  const extraType = (adapter?.typeFields ?? []).map((f) => `    readonly ${f.name}: ${f.tsType};`).join("\n");

  const one = (e) => {
    const lines = [
      `    operationId: ${literal(e.operationId)},`,
      `    method: ${literal(e.method)},`,
      `    path: ${literal(e.path)},`,
      `    successStatuses: [${e.successStatuses.join(", ")}],`,
      `    errorStatuses: [${e.errorStatuses.join(", ")}],`,
      `    requestContentTypes: [${e.requestContentTypes.map(literal).join(", ")}],`,
      `    headerNames: [${e.headerNames.map(literal).join(", ")}],`,
      ...Object.entries(e.fields).map(([k, v]) => `    ${k}: ${literal(v)},`),
      e.schemas.body ? `    body: ${e.schemas.body},` : null,
      e.schemas.pathParams ? `    pathParams: ${e.schemas.pathParams},` : null,
      e.schemas.query ? `    query: ${e.schemas.query},` : null,
      e.schemas.headers ? `    headers: ${e.schemas.headers},` : null,
      `    response: ${e.schemas.response},`,
    ].filter(Boolean);
    return `export const ${e.operationId} = {\n${lines.join("\n")}\n} as const satisfies OperationDefinition;`;
  };

  return `// AUTO-GENERATED by scripts/generate-openapi-types.mjs. Do not edit.
// Regenerate with: npm run generate-api-types
import type { ZodType } from 'zod';

import {
${imports.map((n) => `    ${n},`).join("\n")}
} from './zod.gen';

export type HttpMethod = 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH' | 'OPTIONS' | 'HEAD' | 'TRACE';

/** One operation, exactly as the contract declares it${adapter ? `, with ${adapter.name} fields` : ""}. */
export interface OperationDefinition {
    readonly operationId: string;
    readonly method: HttpMethod;
    readonly path: string;
    readonly successStatuses: readonly number[];
    readonly errorStatuses: readonly number[];
    readonly requestContentTypes: readonly string[];
    readonly headerNames: readonly string[];
${extraType ? extraType + "\n" : ""}    readonly body?: ZodType;
    readonly pathParams?: ZodType;
    readonly query?: ZodType;
    readonly headers?: ZodType;
    readonly response: ZodType;
}

${entries.map(one).join("\n\n")}

/** Every operation the contract declares. */
export const OPERATIONS = [
${entries.map((e) => `    ${e.operationId},`).join("\n")}
] as const;
`;
}

/**
 * Factory returning an `afterGenerate` function. Pass it an adapter (or none for the portable
 * registry alone). The returned function is what openapi.policy.mjs assigns to `afterGenerate`.
 */
export function operationsEmitter({ adapter } = {}) {
  return async function afterGenerate(ctx) {
    const entries = buildRegistry(ctx.operations, ctx.zodExports, adapter);
    writeFileSync(join(ctx.outDir, "operations.gen.ts"), renderRegistry(entries, adapter));

    // Framework-specific extra files (e.g. Fastify's operationId union + 501 stubs).
    if (adapter?.emit) await adapter.emit({ ...ctx, entries });

    // Per-operation conformance (e.g. Next's "the route file exists").
    if (adapter?.check) {
      for (const op of ctx.operations) adapter.check(op, ctx);
    }
  };
}
