// Fastify adapter for the operations emitter, for apps wired with `fastify-openapi-glue`.
//
// Fastify's routing model is the opposite of Next's: there is no per-path route file. Glue
// registers every route FROM the spec at runtime and resolves each to a service method named by
// `operationId`. So this adapter adds no route-file field and runs no file-existence check;
// instead its `emit` writes the operationId-keyed artifacts glue needs:
//   - an `OperationId` union (every operationId the contract declares), and
//   - `stubHandlers`: a 501 problem+json handler per operationId, spread FIRST in the service so
//     an unimplemented operation returns a clean 501 instead of glue's generic 500.
// This is the dependency-free gen-handler-stubs pattern, now fed by the same validated contract
// pass as the rest of the pipeline rather than a standalone regex.
//
// Factory, so it is configurable:
//   fastify()                               // writes handler-stubs.ts beside the generated code
//   fastify({ stubsFile: 'stubs.ts' })      // custom filename
//   fastify({ emitStubs: false })           // just the fastifyPath field + registry

import { writeFileSync } from "node:fs";
import { join } from "node:path";

export function fastify({ stubsFile = "handler-stubs.ts", emitStubs = true } = {}) {
  return {
    name: "fastify",

    fields(op) {
      // OpenAPI `/payments/{id}` -> Fastify `/payments/:id`, handy for logging and manual routes.
      return { fastifyPath: op.path.replace(/\{([^{}]+)\}/g, ":$1") };
    },

    typeFields: [{ name: "fastifyPath", tsType: "string" }],

    emit(ctx) {
      if (!emitStubs) return;
      const ids = [...new Set(ctx.operations.map((o) => o.operationId))].sort();
      const stubs = ids
        .map(
          (id) => `  ${id}: async (_request, reply) => {
    await reply.code(501).type('application/problem+json').send({
      type: 'about:blank',
      title: 'Not Implemented',
      status: 501,
      detail: "Operation '${id}' is declared in the OpenAPI contract but has no handler yet.",
    });
  },`,
        )
        .join("\n");

      const content = `// AUTO-GENERATED by scripts/generate-openapi-types.mjs. Do not edit.
// Regenerate with: npm run generate-api-types
import type { RouteHandlerMethod } from 'fastify';

/** Every operationId the OpenAPI contract declares. */
export type OperationId =
${ids.map((id) => `  | '${id}'`).join("\n")};

/**
 * A 501 stub per operationId. Spread FIRST in the service object passed to fastify-openapi-glue so
 * an unimplemented operation returns a clean 501; real handlers spread afterwards override it.
 */
export const stubHandlers: Record<OperationId, RouteHandlerMethod> = {
${stubs}
};
`;
      writeFileSync(join(ctx.outDir, stubsFile), content);
    },
  };
}
